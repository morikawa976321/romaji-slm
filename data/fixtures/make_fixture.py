# 解析器の読みと zenz の読みが食い違う例（input をわざと書き換える）
MISMATCH = {
    "今日は天気がいいですね。": "キョウワテンキガイイデスヨ",
    "駅まで歩いて十分ほどかかります。": "エキマデアルイテジュップンホドカカリマス",
    "本日は晴天なり。": "ホンニチハセイテンナリ",
    "全然わからない。": "ゼンゼンワカラナイヨ",
}


def main() -> None:
    rows = []
    prev = ""
    for i, text in enumerate(SENTENCES):
        toks = analyze(text)
        reading = "".join(t.sound if t.kind == "ja" else (t.typed if t.kind == "lit" and t.typed.isalpha() else "") for t in toks)
        rows.append({
            "input": MISMATCH.get(text, reading),
            "output": text,
            "left_context": prev if i % 3 == 0 else "",
            "source": "fixture",
        })
        prev = text
    path = Path(__file__).with_name("zenz_like.jsonl")
    with open(path, "w", encoding="utf-8") as f:
        for r in rows:
            f.write(json.dumps(r, ensure_ascii=False) + "\n")
    print(f"{len(rows)} 件 → {path}")


if __name__ == "__main__":
    main()
